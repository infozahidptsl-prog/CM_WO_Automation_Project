using System;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using ClosedXML.Excel;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using WO_CM_Review_Automation.Application.Processing;
using WO_CM_Review_Automation.Application.Reports;
using WO_CM_Review_Automation.Infrastructure.Data;

namespace WO_CM_Review_Automation.Infrastructure.Services;

public class ReportService : IReportService
{
    private readonly ApplicationDbContext _context;
    private readonly IProcessingEngine _processingEngine;
    private readonly IConfiguration _configuration;

    public ReportService(ApplicationDbContext context, IProcessingEngine processingEngine, IConfiguration configuration)
    {
        _context = context;
        _processingEngine = processingEngine;
        _configuration = configuration;
    }

    public async Task<ReportViewModel> GetReportAsync(Guid uploadHistoryId)
    {
        var upload = await _context.UploadHistories
            .FirstOrDefaultAsync(x => x.Id == uploadHistoryId);
            
        if (upload == null)
            throw new Exception("Upload not found.");

        var processingResult = await _processingEngine.ProcessBatchAsync(uploadHistoryId);

        var model = new ReportViewModel
        {
            MonthlySummary = processingResult.MonthlySummary,
            MonthName = upload.UploadDate.ToString("MMMM yyyy"),
            GeneratedBy = "System Administrator", // In reality, inject AuthenticationStateProvider
            GeneratedDate = DateTimeOffset.UtcNow,
            SourceFile = upload.FileName,
            ImportDate = upload.UploadDate,
            TotalWorkOrders = processingResult.MonthlySummary.Items.Sum(x => x.Count)
        };

        return model;
    }

    public async Task<byte[]> GenerateExcelAsync(Guid uploadHistoryId)
    {
        var report = await GetReportAsync(uploadHistoryId);

        using var wb = new XLWorkbook();
        var ws = wb.Worksheets.Add("Monthly Summary");

        // Headers
        ws.Cell(1, 1).Value = "Application Name";
        ws.Cell(1, 2).Value = "Count";
        
        var headerRange = ws.Range(1, 1, 1, 2);
        headerRange.Style.Font.Bold = true;
        headerRange.Style.Border.BottomBorder = XLBorderStyleValues.Thin;
        
        // Data
        int row = 2;
        foreach (var item in report.MonthlySummary.Items)
        {
            ws.Cell(row, 1).Value = item.ApplicationName;
            ws.Cell(row, 2).Value = item.Count;
            row++;
        }
        
        // Total Row
        ws.Cell(row, 1).Value = "TOTAL";
        ws.Cell(row, 2).Value = report.TotalWorkOrders;
        
        var totalRange = ws.Range(row, 1, row, 2);
        totalRange.Style.Font.Bold = true;
        totalRange.Style.Border.TopBorder = XLBorderStyleValues.Thin;
        
        ws.Columns().AdjustToContents();
        ws.SheetView.FreezeRows(1);
        ws.RangeUsed()?.SetAutoFilter();

        using var stream = new MemoryStream();
        wb.SaveAs(stream);
        return stream.ToArray();
    }

    public async Task<byte[]> GeneratePdfAsync(Guid uploadHistoryId)
    {
        var report = await GetReportAsync(uploadHistoryId);
        
        var orgName = _configuration["ReportBranding:OrganizationName"] ?? "WO CM Review Automation";
        var orgDept = _configuration["ReportBranding:OrganizationDepartment"] ?? "Enterprise Change Management";
        var footerText = _configuration["ReportBranding:Footer"] ?? "Generated by WO_CM_Review_Automation";

        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(20, Unit.Millimetre);
                page.PageColor(Colors.White);
                page.DefaultTextStyle(x => x.FontSize(10).FontFamily(Fonts.Arial));

                page.Header().Element(ComposeHeader);
                page.Content().Element(ComposeContent);
                page.Footer().Element(ComposeFooter);

                void ComposeHeader(IContainer c)
                {
                    c.Row(row =>
                    {
                        row.RelativeItem().Column(col =>
                        {
                            col.Item().Text(orgName).FontSize(16).SemiBold();
                            col.Item().Text(orgDept).FontSize(12);
                        });
                        row.ConstantItem(100).AlignRight().Column(col =>
                        {
                            col.Item().Text($"Month: {report.MonthName}").SemiBold();
                            col.Item().Text($"Generated: {report.GeneratedDate:yyyy-MM-dd}");
                        });
                    });
                }

                void ComposeContent(IContainer c)
                {
                    c.PaddingVertical(1, Unit.Centimetre).Column(col =>
                    {
                        col.Item().PaddingBottom(10).Text("Monthly Change Management Summary").FontSize(14).SemiBold();
                        
                        col.Item().Row(r =>
                        {
                            r.RelativeItem().Text($"Source File: {report.SourceFile}");
                            r.RelativeItem().AlignRight().Text($"Import Date: {report.ImportDate:yyyy-MM-dd HH:mm}");
                        });
                        
                        col.Item().PaddingTop(15).Table(table =>
                        {
                            table.ColumnsDefinition(columns =>
                            {
                                columns.RelativeColumn();
                                columns.ConstantColumn(100);
                            });

                            table.Header(header =>
                            {
                                header.Cell().BorderBottom(1).PaddingBottom(5).Text("Application Name").SemiBold();
                                header.Cell().BorderBottom(1).PaddingBottom(5).AlignRight().Text("Count").SemiBold();
                            });

                            foreach (var item in report.MonthlySummary.Items)
                            {
                                table.Cell().PaddingVertical(3).BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Text(item.ApplicationName);
                                table.Cell().PaddingVertical(3).BorderBottom(1).BorderColor(Colors.Grey.Lighten3).AlignRight().Text(item.Count.ToString());
                            }

                            table.Cell().PaddingVertical(5).Text("TOTAL").SemiBold();
                            table.Cell().PaddingVertical(5).AlignRight().Text(report.TotalWorkOrders.ToString()).SemiBold();
                        });
                    });
                }

                void ComposeFooter(IContainer c)
                {
                    c.AlignCenter().Text(x =>
                    {
                        x.Span(footerText).FontSize(8);
                        x.Span(" | Page ").FontSize(8);
                        x.CurrentPageNumber().FontSize(8);
                        x.Span(" of ").FontSize(8);
                        x.TotalPages().FontSize(8);
                    });
                }
            });
        });

        return document.GeneratePdf();
    }
}
